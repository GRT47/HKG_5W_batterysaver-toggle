#!/usr/bin/env python3
"""
Builds the HKG Standard Gen5W 12V Aux Battery Saver+ & Parking Voltage Monitor NEMESIS package:
1. Compiles Java sources (src_stubs + src_java) against android.jar (Java 8 bytecode).
2. Runs self-tests on host JVM (`com.hkg.auxmon.AuxMonMain test-self`).
3. Converts `com/hkg/auxmon/*.class` to Dalvik `classes.dex` (min-api 19, dex version 035)
   using Android SDK `d8`, excluding `com/hkmc/*` compile-time stubs so they bind to
   `/system/framework/automotive.jar` on the headunit at runtime.
4. Packages `classes.dex` into `build/auxmon.jar`.
5. Stages package files with LF line endings and creates:
   - `build/usb_root/packages/hkg.auxmon.zip`
   - `build/HKG_5W_AuxBattery_Monitor_USB.zip` (ready to extract to a FAT32/exFAT USB stick root)
"""

import os
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SDK_ROOT = Path(os.environ.get("ANDROID_SDK_ROOT", r"C:\Users\dlwns\AppData\Local\Android\Sdk"))
ANDROID_JAR = SDK_ROOT / "platforms" / "android-36" / "android.jar"
D8_JAR = SDK_ROOT / "build-tools" / "36.0.0" / "lib" / "d8.jar"

BUILD_DIR = ROOT / "build"
CLASSES_DIR = BUILD_DIR / "classes"
DEX_DIR = BUILD_DIR / "dex"
STAGE_DIR = BUILD_DIR / "pkg_stage"
USB_STAGE_DIR = BUILD_DIR / "usb_root"

JAR_OUT = BUILD_DIR / "auxmon.jar"
PKG_ZIP_OUT = USB_STAGE_DIR / "packages" / "hkg.auxmon.zip"
DIST_ZIP_OUT = BUILD_DIR / "HKG_5W_AuxBattery_Monitor_USB.zip"


def run_cmd(cmd, **kwargs):
    print("+", " ".join(str(c) for c in cmd))
    subprocess.run(cmd, check=True, **kwargs)


def normalize_lf(src: Path, dst: Path):
    dst.parent.mkdir(parents=True, exist_ok=True)
    data = src.read_bytes().replace(b"\r\n", b"\n")
    dst.write_bytes(data)


def main():
    if not ANDROID_JAR.exists():
        print(f"ERROR: android.jar not found at {ANDROID_JAR}", file=sys.stderr)
        sys.exit(1)
    if not D8_JAR.exists():
        print(f"ERROR: d8.jar not found at {D8_JAR}", file=sys.stderr)
        sys.exit(1)

    if BUILD_DIR.exists():
        shutil.rmtree(BUILD_DIR)
    CLASSES_DIR.mkdir(parents=True, exist_ok=True)
    DEX_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Compile Java sources (stubs + main app)
    stub_files = sorted((ROOT / "src_stubs").rglob("*.java"))
    java_files = sorted((ROOT / "src_java").rglob("*.java"))
    all_sources = [str(p) for p in (stub_files + java_files)]

    run_cmd([
        "javac",
        "--release", "8",
        "-encoding", "UTF-8",
        "-cp", str(ANDROID_JAR),
        "-d", str(CLASSES_DIR),
        *all_sources,
    ])

    # 2. Run host JVM self-tests
    sep = ";" if os.name == "nt" else ":"
    run_cmd([
        "java",
        "-cp", f"{CLASSES_DIR}{sep}{ANDROID_JAR}",
        "com.hkg.auxmon.AuxMonMain",
        "test-self",
    ])

    # 3. Convert only com/hkg/auxmon/*.class to Dalvik classes.dex (API 19 -> dex 035)
    # Exclude com/hkmc/* stub classes so runtime resolves against /system/framework/automotive.jar
    app_class_files = sorted((CLASSES_DIR / "com" / "hkg" / "auxmon").rglob("*.class"))
    stub_class_files = sorted((CLASSES_DIR / "com" / "hkmc").rglob("*.class"))

    stubs_jar = BUILD_DIR / "stubs.jar"
    with zipfile.ZipFile(stubs_jar, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for sc in stub_class_files:
            rel = sc.relative_to(CLASSES_DIR).as_posix()
            zf.write(sc, rel)

    d8_cmd = [
        "java", "-cp", str(D8_JAR),
        "com.android.tools.r8.D8",
        "--min-api", "19",
        "--no-desugaring",
        "--lib", str(ANDROID_JAR),
        "--classpath", str(stubs_jar),
        "--output", str(DEX_DIR),
        *[str(c) for c in app_class_files],
    ]
    run_cmd(d8_cmd)

    dex_file = DEX_DIR / "classes.dex"
    if not dex_file.exists():
        raise RuntimeError("classes.dex was not generated by d8")

    magic = dex_file.read_bytes()[:8]
    print(f"Generated classes.dex magic: {magic!r} ({dex_file.stat().st_size} bytes)")
    if magic != b"dex\n035\x00":
        raise RuntimeError(f"Expected Dalvik dex 035 header for KitKat 4.4.2, got {magic!r}")

    # 4. Package classes.dex into build/auxmon.jar
    with zipfile.ZipFile(JAR_OUT, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.write(dex_file, "classes.dex")
    print(f"Created {JAR_OUT} ({JAR_OUT.stat().st_size} bytes)")

    # 5. Stage package files with normalized LF line endings
    if STAGE_DIR.exists():
        shutil.rmtree(STAGE_DIR)
    STAGE_DIR.mkdir(parents=True, exist_ok=True)

    normalize_lf(ROOT / "NEMESIS.data", STAGE_DIR / "NEMESIS.data")
    normalize_lf(ROOT / "bin" / "launch.sh", STAGE_DIR / "bin" / "launch.sh")
    normalize_lf(ROOT / "svc" / "auxmon-daemon.sh", STAGE_DIR / "svc" / "auxmon-daemon.sh")
    normalize_lf(ROOT / "scripts" / "post.sh", STAGE_DIR / "scripts" / "post.sh")
    normalize_lf(ROOT / "scripts" / "preun.sh", STAGE_DIR / "scripts" / "preun.sh")
    shutil.copy2(JAR_OUT, STAGE_DIR / "bin" / "auxmon.jar")

    # 6. Create USB distribution structure:
    #    packages/hkg.auxmon.zip
    if USB_STAGE_DIR.exists():
        shutil.rmtree(USB_STAGE_DIR)
    PKG_ZIP_OUT.parent.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(PKG_ZIP_OUT, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for file_path in sorted(STAGE_DIR.rglob("*")):
            if file_path.is_file():
                rel = file_path.relative_to(STAGE_DIR).as_posix()
                zf.write(file_path, rel)

    print(f"Created package zip: {PKG_ZIP_OUT} ({PKG_ZIP_OUT.stat().st_size} bytes)")

    # Also create an all-in-one USB root zip for easy extraction onto USB stick
    with zipfile.ZipFile(DIST_ZIP_OUT, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for file_path in sorted(USB_STAGE_DIR.rglob("*")):
            if file_path.is_file():
                rel = file_path.relative_to(USB_STAGE_DIR).as_posix()
                zf.write(file_path, rel)

    print(f"Created USB root bundle: {DIST_ZIP_OUT} ({DIST_ZIP_OUT.stat().st_size} bytes)")
    print("\n=== Package Contents (packages/hkg.auxmon.zip) ===")
    with zipfile.ZipFile(PKG_ZIP_OUT, "r") as zf:
        for info in zf.infolist():
            print(f"  {info.filename:30s}  {info.file_size:8d} bytes")


if __name__ == "__main__":
    main()
